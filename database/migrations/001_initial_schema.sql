CREATE TABLE cartridges (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number TEXT NOT NULL,
    model TEXT NOT NULL,
    office TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'ready'
        CHECK (status IN ('ready', 'in_use', 'empty', 'refilling')),
    received_at TIMESTAMPTZ,
    sent_to_refill_at TIMESTAMPTZ,
    ready_at TIMESTAMPTZ,
    issued_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE cartridge_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cartridge_id BIGINT NOT NULL REFERENCES cartridges(id) ON DELETE RESTRICT,
    action TEXT NOT NULL CHECK (action IN ('created', 'updated', 'statusChanged')),
    old_status TEXT CHECK (
        old_status IS NULL OR old_status IN ('ready', 'in_use', 'empty', 'refilling')
    ),
    new_status TEXT CHECK (
        new_status IS NULL OR new_status IN ('ready', 'in_use', 'empty', 'refilling')
    ),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    changed_by TEXT NOT NULL,
    comment TEXT,
    CHECK (
        action <> 'statusChanged'
        OR (old_status IS NOT NULL AND new_status IS NOT NULL AND old_status <> new_status)
    )
);

CREATE INDEX cartridges_number_idx ON cartridges (number);
CREATE INDEX cartridges_office_idx ON cartridges (office);
CREATE INDEX cartridges_status_idx ON cartridges (status);
CREATE INDEX cartridge_logs_cartridge_occurred_idx
    ON cartridge_logs (cartridge_id, occurred_at DESC);

CREATE FUNCTION cartlog_set_updated_at() RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER cartridges_set_updated_at
    BEFORE UPDATE ON cartridges
    FOR EACH ROW
    EXECUTE FUNCTION cartlog_set_updated_at();
